# ── Apply conversions ───────────────────────────────────────────────────────
converted = 0
for failure in d["failures"]:
    cs = failure.get("case_studies", [])
    if not cs or not isinstance(cs[0], str):
        continue
    new_cs = []
    for item in cs:
        if item in REPLACEMENTS:
            new_cs.append(REPLACEMENTS[item])
        else:
            # Fallback: wrap unknown string in minimal dict
            new_cs.append({
                "title": item,
                "system": "Unknown",
                "date": "Unknown",
                "outcome": item,
                "source": "Prior session enrichment"
            })
    failure["case_studies"] = new_cs
    converted += 1
    print(f"Converted: {failure['id']}")

print(f"\nConverted {converted} classes to structured dict format")

